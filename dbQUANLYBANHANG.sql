CREATE OR ALTER PROCEDURE dbo.psInsertRecordSANPHAM
    @TENSANPHAM NVARCHAR(150),
    @DONGIA DECIMAL(18,2),
    @SOLUONG INT,
    @HINHANH NVARCHAR(255) = NULL,
    @MOTA NVARCHAR(MAX) = NULL,
    @MADANHMUC INT = NULL
AS
BEGIN
