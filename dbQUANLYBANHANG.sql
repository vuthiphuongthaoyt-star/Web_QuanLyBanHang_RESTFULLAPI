CREATE OR ALTER PROCEDURE dbo.psInsertRecordCTDONHANG
    @MADONHANG INT,
    @MASANPHAM INT,
    @TENSANPHAM NVARCHAR(150),
    @SOLUONG INT,
    @DONGIA DECIMAL(18,2)
AS
BEGIN
    INSERT INTO CTDONHANG(MADONHANG, MASANPHAM, TENSANPHAM, SOLUONG, DONGIA)
    VALUES(@MADONHANG, @MASANPHAM, @TENSANPHAM, @SOLUONG, @DONGIA);

    UPDATE SANPHAM
    SET SOLUONG = CASE WHEN SOLUONG - @SOLUONG < 0 THEN 0 ELSE SOLUONG - @SOLUONG END
    WHERE MASANPHAM = @MASANPHAM;
END
GO

