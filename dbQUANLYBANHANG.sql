IF OBJECT_ID(N'dbo.TAIKHOAN', N'U') IS NULL
CREATE TABLE dbo.TAIKHOAN(
    TENDANGNHAP NVARCHAR(50)  NOT NULL,
    MATKHAU     NVARCHAR(50)  NOT NULL,
    HOTEN       NVARCHAR(100) NULL,
    EMAIL       NVARCHAR(100) NULL,
    DIENTHOAI   NVARCHAR(20)  NULL,
    DIACHI      NVARCHAR(255) NULL,
    QUYEN       BIT           NOT NULL CONSTRAINT DF__TAIKHOAN__QUYEN DEFAULT (0),
    CONSTRAINT PK_TAIKHOAN PRIMARY KEY CLUSTERED (TENDANGNHAP ASC)
)
GO

IF OBJECT_ID(N'dbo.DANHMUC', N'U') IS NULL
CREATE TABLE dbo.DANHMUC(
    MADANHMUC  INT IDENTITY(1,1) NOT NULL,
    TENDANHMUC NVARCHAR(100) NOT NULL,
    MOTA       NVARCHAR(255) NULL,
    CONSTRAINT PK_DANHMUC PRIMARY KEY CLUSTERED (MADANHMUC ASC)
)
GO

IF OBJECT_ID(N'dbo.SANPHAM', N'U') IS NULL
CREATE TABLE dbo.SANPHAM(
    MASANPHAM  INT IDENTITY(1,1) NOT NULL,
    TENSANPHAM NVARCHAR(150) NOT NULL,
    DONGIA     DECIMAL(18,2) NOT NULL CONSTRAINT DF__SANPHAM__DONGIA  DEFAULT (0),
    SOLUONG    INT           NOT NULL CONSTRAINT DF__SANPHAM__SOLUONG DEFAULT (0),
    HINHANH    NVARCHAR(255) NULL,
    MOTA       NVARCHAR(MAX) NULL,
    MADANHMUC  INT           NULL,
    CONSTRAINT PK_SANPHAM PRIMARY KEY CLUSTERED (MASANPHAM ASC),
    CONSTRAINT FK_SANPHAM_DANHMUC FOREIGN KEY (MADANHMUC) REFERENCES dbo.DANHMUC(MADANHMUC)
)
GO

IF OBJECT_ID(N'dbo.DONHANG', N'U') IS NULL
CREATE TABLE dbo.DONHANG(
    MADONHANG       INT IDENTITY(1,1) NOT NULL,
    TENDANGNHAP     NVARCHAR(50)  NULL,
    HOTENNGUOINHAN  NVARCHAR(100) NOT NULL,
    DIACHINHAN      NVARCHAR(255) NOT NULL,
    DIENTHOAINHAN   NVARCHAR(20)  NOT NULL,
    NGAYDAT         DATETIME      NOT NULL CONSTRAINT DF__DONHANG__NGAYDAT   DEFAULT (GETDATE()),
    TONGTIEN        DECIMAL(18,2) NOT NULL CONSTRAINT DF__DONHANG__TONGTIEN DEFAULT (0),
    TRANGTHAI       NVARCHAR(50)  NOT NULL CONSTRAINT DF__DONHANG__TRANGTHAI DEFAULT (N'Chờ xử lý'),
    CONSTRAINT PK_DONHANG PRIMARY KEY CLUSTERED (MADONHANG ASC),
    CONSTRAINT FK_DONHANG_TAIKHOAN FOREIGN KEY (TENDANGNHAP) REFERENCES dbo.TAIKHOAN(TENDANGNHAP)
)
GO

IF OBJECT_ID(N'dbo.CTDONHANG', N'U') IS NULL
CREATE TABLE dbo.CTDONHANG(
    MADONHANG  INT           NOT NULL,
    MASANPHAM  INT           NOT NULL,
    TENSANPHAM NVARCHAR(150) NOT NULL,
    SOLUONG    INT           NOT NULL,
    DONGIA     DECIMAL(18,2) NOT NULL,
    CONSTRAINT PK_CTDONHANG PRIMARY KEY CLUSTERED (MADONHANG ASC, MASANPHAM ASC),
    CONSTRAINT FK_CTDONHANG_DONHANG FOREIGN KEY (MADONHANG) REFERENCES dbo.DONHANG(MADONHANG)
)
GO

CREATE OR ALTER PROCEDURE dbo.psGetTableDANHMUC
    @MADANHMUC INT = NULL
AS
BEGIN
    IF @MADANHMUC IS NULL
        SELECT * FROM DANHMUC ORDER BY TENDANHMUC;
    ELSE
        SELECT * FROM DANHMUC WHERE MADANHMUC = @MADANHMUC;
END
GO

CREATE OR ALTER PROCEDURE dbo.psInsertRecordDANHMUC
    @TENDANHMUC NVARCHAR(100),
    @MOTA NVARCHAR(255) = NULL
AS
BEGIN
    INSERT INTO DANHMUC(TENDANHMUC, MOTA) VALUES(@TENDANHMUC, @MOTA);
END
GO

CREATE OR ALTER PROCEDURE dbo.psUpdateRecordDANHMUC
    @MADANHMUC INT,
    @TENDANHMUC NVARCHAR(100),
    @MOTA NVARCHAR(255) = NULL
AS
BEGIN
    UPDATE DANHMUC SET TENDANHMUC = @TENDANHMUC, MOTA = @MOTA WHERE MADANHMUC = @MADANHMUC;
END
GO

CREATE OR ALTER PROCEDURE dbo.psDeleteRecordDANHMUC
    @MADANHMUC INT
AS
BEGIN
    DELETE FROM DANHMUC WHERE MADANHMUC = @MADANHMUC;
END
GO

CREATE OR ALTER PROCEDURE dbo.psGetTableSANPHAM
