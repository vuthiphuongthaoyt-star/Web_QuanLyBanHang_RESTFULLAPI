GO

CREATE OR ALTER PROCEDURE dbo.psUpdateRecordSANPHAM
    @MASANPHAM INT,
    @TENSANPHAM NVARCHAR(150),
    @DONGIA DECIMAL(18,2),
    @SOLUONG INT,
    @HINHANH NVARCHAR(255) = NULL,
    @MOTA NVARCHAR(MAX) = NULL,
    @MADANHMUC INT = NULL
AS
BEGIN
    UPDATE SANPHAM SET
        TENSANPHAM = @TENSANPHAM,
        DONGIA = @DONGIA,
        SOLUONG = @SOLUONG,
        HINHANH = ISNULL(@HINHANH, HINHANH),
        MOTA = @MOTA,
        MADANHMUC = @MADANHMUC
    WHERE MASANPHAM = @MASANPHAM;
END
GO

